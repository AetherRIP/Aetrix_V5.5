"""Build the production environment file for the VM from the local backend/.env.

Values are copied, never printed. Production-only overrides are applied
explicitly; development-only variables are dropped so the deployed process
cannot fall back into development behaviour.
"""

from __future__ import annotations

import pathlib
import sys

SRC = pathlib.Path("backend/.env")
OUT = pathlib.Path(".tmp/dep/aetrix.env")

DROP = {
    "AETRIX_TEST_DATABASE_URL",
    "AETRIX_AUTH__DEV_MODE",
    "AETRIX_AUTH__DEV_TENANT_ID",
    "AETRIX_AUTH__DEV_USER_ID",
    "AETRIX_PROVIDER__PINNED_CREDENTIAL_ID",
}

OVERRIDE = {
    "AETRIX_ENV": "production",
    "AETRIX_DEBUG": "false",
    "AETRIX_STORAGE__ROOT": "/opt/aetrix/shared/documents",
    "AETRIX_CORS_ORIGINS": "https://aetrix.pages.dev",
}

#: The live provider stays off unless the source environment turns it on
#: explicitly.  This used to be a hard override that rewrote every generated
#: production file to ``false``, so a flag set by hand on the VM was silently
#: undone the next time the environment was generated and Manual Correction kept
#: reporting ``ProviderNotConfigured``.
LIVE_PROVIDER_KEY = "AETRIX_FEATURES__LIVE_PROVIDER"

REQUIRED = {
    "AETRIX_DATABASE__URL",
    "AETRIX_SECURITY__ENCRYPTION_KEY",
    "AETRIX_AUTH__SUPABASE_URL",
    "AETRIX_AUTH__JWKS_URL",
}


def parse(path: pathlib.Path) -> dict[str, str]:
    values: dict[str, str] = {}
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        key = key.strip()
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        values[key] = value
    return values


def main() -> int:
    values = parse(SRC)
    for name in DROP:
        values.pop(name, None)
    values.update(OVERRIDE)
    values.setdefault(LIVE_PROVIDER_KEY, "false")

    missing = sorted(REQUIRED - values.keys())
    if missing:
        print(f"missing required keys: {missing}", file=sys.stderr)
        return 1

    unresolved = [k for k, v in values.items() if "${" in v]
    if unresolved:
        print(f"unresolved interpolations: {unresolved}", file=sys.stderr)
        return 1

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "# Aetrix production environment — generated by deploy/gen_env.py.\n"
        "# Secrets live here only; the file is root:aetrix 0640 and never in Git.\n"
        + "\n".join(f"{k}={values[k]}" for k in sorted(values))
        + "\n",
        encoding="utf-8",
    )
    OUT.chmod(0o600)

    print(f"wrote {OUT} with {len(values)} variables")
    for name in sorted(values):
        value = values[name]
        secret = any(t in name for t in ("KEY", "SECRET", "PASSWORD", "URL"))
        print(f"  {name} = {'<redacted>' if secret else value}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
